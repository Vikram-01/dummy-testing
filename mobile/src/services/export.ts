import { File, Paths } from 'expo-file-system';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { inr } from '@/lib/format';

/**
 * Exports are generated on the device from data already on screen, written to the app's private
 * cache, handed to the Android share sheet, then deleted. Nothing is uploaded by the app.
 */

function csvCell(v: unknown): string {
  const s = v == null ? '' : String(v);
  // Neutralise spreadsheet formula injection.
  const safe = /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
  return /[",\n]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
}

export function toCsv(header: string[], rows: (string | number | null | undefined)[][]): string {
  return [header, ...rows].map((r) => r.map(csvCell).join(',')).join('\r\n');
}

const esc = (s: string) => s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

export type ReportSection = { heading: string; header: string[]; rows: (string | number)[][]; numericCols?: number[] };

export function toHtml(title: string, subtitle: string, sections: ReportSection[], isDemo: boolean): string {
  const tables = sections.map((s) => `
    <h2>${esc(s.heading)}</h2>
    <table>
      <thead><tr>${s.header.map((h, i) => `<th class="${s.numericCols?.includes(i) ? 'n' : ''}">${esc(h)}</th>`).join('')}</tr></thead>
      <tbody>${s.rows.map((r) => `<tr>${r.map((c, i) => `<td class="${s.numericCols?.includes(i) ? 'n' : ''}">${esc(typeof c === 'number' ? inr(c) : c)}</td>`).join('')}</tr>`).join('')}</tbody>
    </table>`).join('');
  return `<!doctype html><html><head><meta charset="utf-8"><style>
    body{font-family:-apple-system,Roboto,Arial,sans-serif;color:#0E1726;margin:32px;font-size:12px}
    h1{font-size:22px;margin:0} .sub{color:#5B6678;margin:4px 0 20px}
    h2{font-size:14px;margin:24px 0 8px;border-bottom:1px solid #E2E6EC;padding-bottom:4px}
    table{width:100%;border-collapse:collapse} th,td{padding:6px 4px;text-align:left;border-bottom:1px solid #F0F2F5}
    th{color:#5B6678;font-weight:600} .n{text-align:right;font-variant-numeric:tabular-nums}
    .demo{background:#F1EAFE;color:#7A3FF2;padding:8px 12px;border-radius:8px;font-weight:700;margin-bottom:16px}
    footer{margin-top:28px;color:#8A94A6;font-size:10px}
  </style></head><body>
    ${isDemo ? '<div class="demo">DEMO DATA — fictional figures for testing only. Not real financial information.</div>' : ''}
    <h1>${esc(title)}</h1><div class="sub">${esc(subtitle)}</div>
    ${tables}
    <footer>Generated by Personal Finance 360 on ${esc(new Date().toLocaleString())}. Confidential.</footer>
  </body></html>`;
}

async function share(uri: string, mimeType: string, dialogTitle: string) {
  if (!(await Sharing.isAvailableAsync())) throw new Error('Sharing is not available on this device');
  await Sharing.shareAsync(uri, { mimeType, dialogTitle });
}

export async function exportCsv(fileBase: string, csv: string) {
  await exportText(`${fileBase}.csv`, '\uFEFF' + csv, 'text/csv'); // BOM so Excel reads ₹ correctly
}

export async function exportText(fileName: string, text: string, mimeType: string) {
  const f = new File(Paths.cache, fileName);
  if (f.exists) f.delete();
  f.create();
  f.write(text);
  try {
    await share(f.uri, mimeType, 'Save or share');
  } finally {
    setTimeout(() => { try { f.delete(); } catch { /* already gone */ } }, 60_000);
  }
}

export async function exportPdf(html: string) {
  const { uri } = await Print.printToFileAsync({ html });
  const f = new File(uri);
  try {
    await share(uri, 'application/pdf', 'Export PDF');
  } finally {
    setTimeout(() => { try { f.delete(); } catch { /* already gone */ } }, 60_000);
  }
}
